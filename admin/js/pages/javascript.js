// JavaScript: the code that Silence generates for the student's web app, in tabs:
//   #/js            API: the JS API (one file per table, to call its endpoints), its settings and
//                   generating it; #/js/file/<name> shows the code of one of its files;
//   #/js/molds      Molds: the molds that the project brings from its template (.silence/js_api/),
//                   which Silence fills in (it has no front-end code of its own); #/js/mold/<name>.
// The files are only read here: the JS API is generated with the endpoints, from the molds.
import { html, tabs, iconButton, muted, link, switchRow } from "../lib/html.js";
import { api } from "../lib/api.js";
import { attempt, toast, needsConfirm } from "../lib/ui.js";
import { formValues } from "../lib/forms.js";
import { readConfig, saveConfig, readFile, listFiles } from "../lib/files.js";
import { dataTable } from "../components/table.js";

const MOLDS = ".silence/js_api";
const TABS = { api: "API", molds: "Molds" };

// What each mold is for, and its holes (docs/molds.md of silence-py)
const MOLD_INFO = {
  "table.js": ["The file of a table", ["table", "functions"]],
  "function.js": ["A function, for each endpoint of the table",
    ["name", "description", "method", "METHOD", "route", "params", "args", "body"]],
  "function_one.js": ["A function that returns one row (getById); optional: without it, function.js",
    ["name", "description", "method", "METHOD", "route", "params", "args", "body"]],
  "common.js": ["What the files share (the base URL, the session header…)", ["api_prefix"]],
};

export function crumbs(params) {
  const [view, name] = params;
  const base = { label: "JavaScript", href: "#/js" };
  if (view === "file") return [base, { label: name }];
  if (view === "mold") return [base, { label: "Molds", href: "#/js/molds" }, { label: name }];
  return [base, { label: TABS[view] ?? TABS.api }];
}

export const parent = (params) => (params[0] === "file" ? "#/js" : params[0] === "mold" ? "#/js/molds" : null);

export async function render(main, app, params) {
  const [view, name] = params;
  if (view === "file") return codePage(main, `${app.status.jsApi.dir}/${name}`, "Generated by Silence from the molds: it is "
    + "overwritten every time the endpoints are generated.");
  if (view === "mold") return moldPage(main, name);
  const tab = TABS[view] ? view : "api";
  main.innerHTML = html`
    <h1>JavaScript</h1>
    ${tabs(Object.entries(TABS).map(([key, label]) => ({ key, label, href: key === "api" ? "#/js" : `#/js/${key}` })), tab)}
    <div id="tab"></div>`;
  const body = main.querySelector("#tab");
  return tab === "api" ? apiTab(body, app) : moldsTab(body, app);
}

///////////////////////////////////////////////////////////////////////////////
// API
///////////////////////////////////////////////////////////////////////////////

async function apiTab(body, app) {
  const js = app.status.jsApi;
  const config = await attempt(() => readConfig());
  if (!config) return;
  const files = js.notGenerated ? [] : await listFiles(js.dir).catch(() => []);
  const rows = files.map((f) => ({ name: f.path.split("/").pop(), path: f.path }));

  body.innerHTML = html`
    <p class="uk-text-muted">Silence generates a JavaScript file for each table and view, with a function for each of its
      endpoints, to call your API from your web app. It is generated with the endpoints (<em>Generate from the
      database</em>, or <code>silence createapi</code>), filling in the molds that your project brings from its template:
      see <a href="#/js/molds">Molds</a>.</p>
    ${js.notGenerated
      ? html`<div class="uk-alert uk-alert-warning">The JS API is not generated: ${js.notGenerated}.</div>`
      : html`<p>Generated in <code>${js.dir}/</code>: ${rows.length} files.</p>`}
    <div class="sa-toolbar">
      <button class="uk-button uk-button-primary" type="button" id="generate" ${js.notGenerated ? "disabled" : ""}>
        Generate the endpoints and the JS API</button>
    </div>
    <div id="grid"></div>
    <h3>Settings</h3>
    <form class="sa-settings" id="settings">
      ${switchRow({ checked: config.config.js_api.enabled, label: "Generate the JS API with the endpoints",
        attrs: { name: "enabled", "data-section": "js_api" } }, "Generate the JS API with the endpoints")}
      <div class="sa-form"><div class="sa-field"><label class="uk-form-label" for="js-dir">Folder</label>
        <input class="uk-input" id="js-dir" data-section="js_api" name="dir" value="${config.config.js_api.dir}"></div></div>
      <div class="sa-toolbar"><button class="uk-button uk-button-default" type="submit">Save</button></div>
    </form>`;

  dataTable(body.querySelector("#grid"), {
    rows, sort: { key: "name", dir: "asc" },
    empty: js.notGenerated ? "Nothing generated." : "No files yet: generate the endpoints.",
    columns: [
      { key: "actions", label: "", filter: false, sortable: false, className: "sa-actions",
        render: (f) => iconButton("code", "See its code", { href: link("js", "file", f.name) }) },
      { key: "name", label: "File", render: (f) => html`<a class="sa-route" href="${link("js", "file", f.name)}">${f.name}</a>` },
      { key: "path", label: "Path", render: (f) => html`<span class="uk-text-muted sa-small">${f.path}</span>` },
    ],
  });

  const generate = body.querySelector("#generate");
  generate.addEventListener("click", async () => {
    if (!needsConfirm(generate, "Overwrite the auto_ files?")) return;
    const res = await attempt(() => api("/endpoints/generate", "POST", {}));
    if (!res) return;
    toast(res.jsApi.notGenerated ? `Endpoints generated; the JS API is not: ${res.jsApi.notGenerated}`
      : `Endpoints and JS API generated in ${res.jsApi.dir}/`, res.jsApi.notGenerated ? "warning" : "success");
    await app.refreshStatus();
    apiTab(body, app);
  });
  body.querySelector("#settings").addEventListener("submit", async (event) => {
    event.preventDefault();
    const values = formValues(event.currentTarget, { bySection: true }).js_api;
    if (await attempt(() => saveConfig("js_api", values), "Saved in silence.json")) {
      await app.refreshStatus();
      apiTab(body, app);
    }
  });
}

///////////////////////////////////////////////////////////////////////////////
// Molds
///////////////////////////////////////////////////////////////////////////////

async function moldsTab(body, app) {
  const template = app.info?.versions?.template;
  const files = await listFiles(MOLDS).catch(() => []);
  const present = new Set(files.map((f) => f.path.split("/").pop()));
  const rows = Object.entries(MOLD_INFO).map(([name, [what, holes]]) => ({ name, what, holes, present: present.has(name) }));

  body.innerHTML = html`
    <p class="uk-text-muted">Silence has no front-end code of its own: it fills in these molds, which your project brings
      from its template in <code>${MOLDS}/</code>. Change them (with your editor) to change the code that is generated,
      for example to use <code>fetch</code> instead of axios; the next generation uses them.</p>
    <p>Template: ${template ? html`<code>${template.repo}</code>, version <code>${template.version}</code>` : muted("not known")}.</p>
    ${present.size ? "" : html`<div class="uk-alert uk-alert-warning">This project has no molds of the JS API, so it is not
      generated: they come with the template (for example, <code>silence-template-v3-ez-ui</code>).</div>`}
    <div id="grid"></div>`;

  dataTable(body.querySelector("#grid"), {
    rows, sort: { key: "name", dir: "asc" },
    columns: [
      { key: "actions", label: "", filter: false, sortable: false, className: "sa-actions",
        render: (m) => (m.present ? iconButton("code", "See it", { href: link("js", "mold", m.name) }) : "") },
      { key: "name", label: "Mold", render: (m) => (m.present
        ? html`<a class="sa-route" href="${link("js", "mold", m.name)}">${m.name}</a>` : html`<span class="sa-route">${m.name}</span>`) },
      { key: "what", label: "What it is", filter: false },
      { key: "holes", label: "Holes", filter: false, sortable: false,
        render: (m) => html`${m.holes.map((h, i) => html`${i ? " " : ""}<code>{{${h}}}</code>`)}` },
      { key: "present", label: "In the project", filter: "select", value: (m) => (m.present ? "yes" : "no"),
        render: (m) => (m.present ? "yes" : m.name === "function_one.js" ? muted("no (function.js)") : html`<span class="sa-fail">no</span>`) },
    ],
  });
}

///////////////////////////////////////////////////////////////////////////////
// The code of a file
///////////////////////////////////////////////////////////////////////////////

async function codePage(main, path, note) {
  const file = await attempt(() => readFile(path));
  if (!file) return;
  main.innerHTML = html`
    <h1><code>${path.split("/").pop()}</code></h1>
    <p class="uk-text-muted sa-small"><code>${path}</code>. ${note}</p>
    ${file.data === null ? html`<div class="uk-alert uk-alert-warning">There is no ${path}.</div>`
      : html`<pre class="sa-pre sa-code-view">${file.data}</pre>`}`;
}

function moldPage(main, name) {
  const [what, holes] = MOLD_INFO[name] ?? ["A mold", []];
  return codePage(main, `${MOLDS}/${name}`, html`${what}. Holes: ${holes.map((h, i) => html`${i ? ", " : ""}<code>{{${h}}}</code>`)}.`);
}
