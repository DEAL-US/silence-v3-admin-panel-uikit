function same(expected, actual) {
  if (typeof expected === "number" && typeof actual === "number") return expected === actual;
  return JSON.stringify(expected) === JSON.stringify(actual);
}

/** The failures of a response against what a unit test expects (as Silence checks them). */
function check(expect, status, data) {
  const failures = [];
  if (expect.status !== undefined) {
    if (expect.status !== status) failures.push(`expected status ${expect.status}, got ${status}`);
  } else if (!(status >= 200 && status < 300)) {
    failures.push(`expected a 2xx status, got ${status}`);
  }
  if (expect.count !== undefined) {
    const n = Array.isArray(data) ? data.length : null;
    if (n !== expect.count) failures.push(`expected ${expect.count} rows, got ${n}`);
  }
  if (expect.row !== undefined) {
    const row = Array.isArray(data) ? data[0] : data;
    if (!row || typeof row !== "object") {
      failures.push("expected a row, got none");
    } else {
      for (const [k, v] of Object.entries(expect.row)) {
        if (!same(v, row[k])) failures.push(`expected ${k} = ${JSON.stringify(v)}, got ${JSON.stringify(row[k])}`);
      }
    }
  }
  if (expect.message !== undefined) {
    const msg = data && typeof data === "object" && !Array.isArray(data) ? data.message ?? "" : "";
    if (!msg.includes(expect.message)) failures.push(`expected a message with ${JSON.stringify(expect.message)}, got ${JSON.stringify(msg)}`);
  }
  return failures;
}

/** The request and the expectation of a unit test as written in its file: the short form
 *  ({"METHOD /path": body, "as": id, "expect": status | {...}}) or the long one ({request, expect}). */
function parseUnit(def) {
  if (!def || typeof def !== "object" || Array.isArray(def)) throw new Error("A test is an object");
  if (def.steps) throw new Error("A unit test has one request: the composite tests go in the Composite tab");
  let request;
  if (def.request) {
    request = { method: String(def.request.method ?? "GET").toUpperCase(), path: def.request.path, body: def.request.body ?? null,
      as: def.request.as ?? null };
  } else {
    const keys = Object.keys(def).filter((k) => /^(GET|POST|PUT|DELETE)\s+\//i.test(k));
    if (keys.length !== 1) throw new Error('Write one request as "METHOD /path": body (e.g. "GET /employees/1": null)');
    const [m, path] = keys[0].trim().split(/\s+/);
    request = { method: m.toUpperCase(), path, body: def[keys[0]], as: def.as ?? null };
  }
  if (!request.path) throw new Error("The request has no path");
  let expect = def.expect ?? {};
  if (typeof expect === "number") expect = { status: expect };
  return { request, expect };
}

/** Runs a unit test against the student's API and returns its result (a step).
 *  tokens: the sessions already opened in this run, by user; token: a session to use when the
 *  test has no "as" (the one of a previous login, in a composite test). */
async function runUnit(name, unit, { source, tokens = new Map(), token = null, index = 0 } = {}) {
  const req = unit.request;
  let stepToken = token;
  if (req.as !== null && req.as !== undefined) {
    if (!tokens.has(String(req.as))) {
      try {
        const s = await api(`/users/${encodeURIComponent(req.as)}/session`, "POST", undefined, undefined, { quiet: true });
        tokens.set(String(req.as), s.sessionToken);
      } catch (error) {
        return { index, test: name, method: req.method, path: req.path, passed: false,
          failures: [`Cannot open a session as user ${req.as}: ${error.message}`] };
      }
    }
    stepToken = tokens.get(String(req.as));
  }
  const res = await callApi(studentApi.prefix, req.method, req.path, req.body, {
    source: req.as !== null && req.as !== undefined ? `${source} (as ${req.as})` : source, token: stepToken,
    expect: (status, data) => check(unit.expect, status, data).length === 0,
  });
  const failures = check(unit.expect, res.status, res.data);
  return { index, test: name, method: req.method, path: req.path, status: res.status, response: res.data,
    failures, passed: failures.length === 0 };
}

/** Runs a composite test: its unit tests, in order, against the student's API. A step that logs
 *  in (its response has a sessionToken) gives its session to the next steps that have no "as".
 *  It stops at the first step that fails. */
async function runComposite(composite, units) {
  const byName = Object.fromEntries(units.map((u) => [u.name, u]));
  const tokens = new Map();
  let token = null;
  const steps = [];
  for (const [index, name] of composite.steps.entries()) {
    const unit = byName[name];
    if (!unit) {
      steps.push({ index, test: name, method: "", path: "", passed: false, failures: [`There is no unit test ${name}`] });
      break;
    }
    const step = await runUnit(name, unit, { source: `Composite ${composite.name}`, tokens, token, index });
    if (step.response && typeof step.response === "object" && typeof step.response.sessionToken === "string") {
      token = step.response.sessionToken;
    }
    steps.push(step);
    if (!step.passed) break;
  }
  return { passed: steps.length === composite.steps.length && steps.every((s) => s.passed), steps };
}

async function saveComposites(list, etag) {
  return attempt(() => api(`/panel-data/${COMPOSITE_DATA}`, "PUT", list, etag ?? ""));
}

async function compositeList(main) {
  const all = await loadAll();
  if (!all) return;
  const names = new Set(all.units.map((u) => u.name));
  const resultOf = (c) => results["composite:" + c.name];

  main.innerHTML = `
    <h1>Tests</h1>
    <p class="uk-text-muted">Composite tests: unit tests run one after another by this panel, against your API.
      <strong>They change the database</strong> (they are not rolled back). A step that logs in gives its session to the
      next steps. The panel saves them in <code>admin/data/composite_tests.json</code>.</p>
    ${tabsHtml("composite", all.counts)}
    <div class="sa-toolbar">
      <a class="uk-button uk-button-primary" href="#/tests/composite/new">New composite test</a>
    </div>
    <div id="grid"></div>`;

  const table = dataTable(main.querySelector("#grid"), {
    rows: all.composites, sort: { key: "name", dir: "asc" }, empty: "No composite tests yet.",
    columns: [
      { key: "actions", label: "", filter: false, sortable: false, className: "sa-actions", render: (c) =>
        iconButton("play", "Run (changes the database)", { action: "run" }) +
        iconButton("pencil", "Edit", { href: link("tests", "composite", "edit", c.name) }) +
        iconButton("trash", "Delete", { action: "delete", danger: true }) },
      { key: "result", label: "Result", filter: "select",
        value: (c) => (resultOf(c) ? (resultOf(c).passed ? "PASS" : "FAIL") : ""), render: (c) => resultBadge(resultOf(c)) },
      { key: "name", label: "Test", render: (c) => `<strong>${esc(c.name)}</strong>` },
      { key: "steps", label: "Steps", filter: false, value: (c) => c.steps.length },
      { key: "units", label: "Unit tests", value: (c) => c.steps.join(" "), render: (c) =>
        c.steps.map((s) => names.has(s) ? `<code class="sa-unit">${esc(s)}</code>`
          : `<code class="sa-unit sa-unit--missing" title="There is no unit test with this name">${esc(s)}</code>`).join(" → ") },
    ],
    after: (c) => (resultOf(c) && !resultOf(c).passed ? stepsDetail(resultOf(c).steps) : ""),
    onAction: async (action, c, button) => {
      if (action === "run") {
        if (!needsConfirm(button, "Run? It changes the database")) return;
        const r = await runComposite(c, all.units);
        results["composite:" + c.name] = r;
        toast(`${c.name}: ${r.passed ? "passed" : "failed"} (${r.steps.filter((s) => s.passed).length} of ${c.steps.length} steps)`,
          r.passed ? "success" : "warning");
        table.update(all.composites);
      }
      if (action === "delete") {
        if (!needsConfirm(button, "Delete?")) return;
        const list = all.composites.filter((x) => x.name !== c.name);
        if (await saveComposites(list, all.compositeEtag)) {
          delete results["composite:" + c.name];
          toast("Deleted", "success");
          compositeList(main);
        }
      }
    },
  });
}

async function compositeEditor(main, name) {
  const all = await loadAll();
  if (!all) return;
  const original = name ? all.composites.find((c) => c.name === name) : null;
  if (name && !original) {
    main.innerHTML = `<div class="uk-alert uk-alert-danger">There is no composite test ${esc(name)}.</div>`;
    return;
  }
  const unitNames = all.units.map((u) => u.name).sort();
  const steps = [...(original?.steps ?? [])];

  main.innerHTML = `
    <h1>${original ? `Edit ${esc(original.name)}` : "New composite test"}</h1>
    <form id="composite-form">
      <div class="sa-form">
        <div class="sa-field"><label class="uk-form-label" for="c-name">Name</label>
          <input class="uk-input" id="c-name" value="${esc(original?.name ?? "")}" required pattern="\\w+"></div>
        <div class="sa-field"><label class="uk-form-label" for="c-desc">Description</label>
          <input class="uk-input" id="c-desc" value="${esc(original?.description ?? "")}"></div>
      </div>
      <h2>Steps</h2>
      <ol class="sa-steps-list" id="c-steps"></ol>
      <div class="sa-toolbar">
        <select class="uk-select sa-step-select" id="c-add-name" aria-label="Unit test to add">
          ${unitNames.map((n) => `<option>${esc(n)}</option>`).join("")}
        </select>
        <button class="uk-button uk-button-default" type="button" id="c-add">Add step</button>
      </div>
      <div class="sa-toolbar">
        <button class="uk-button uk-button-primary" type="submit">Save</button>
        <a class="uk-button uk-button-default" href="#/tests/composite">Cancel</a>
      </div>
    </form>`;

  const list = main.querySelector("#c-steps");
  function drawSteps() {
    list.innerHTML = steps.length ? steps.map((s, i) => `
      <li data-i="${i}">
        <code class="sa-unit${unitNames.includes(s) ? "" : " sa-unit--missing"}">${esc(s)}</code>
        ${unitNames.includes(s) ? "" : `<span class="uk-text-danger sa-small">(it does not exist)</span>`}
        <span class="sa-toolbar__spacer"></span>
        ${iconButton("arrow-up", "Move up", { action: "up" })}${iconButton("arrow-down", "Move down", { action: "down" })}${iconButton("close", "Remove", { action: "remove", danger: true })}
      </li>`).join("") : `<li class="uk-text-muted sa-steps-list__empty">No steps yet: add unit tests below.</li>`;
  }
  list.addEventListener("click", (event) => {
    const button = event.target.closest("[data-action]");
    if (!button) return;
    const i = Number(button.closest("li").dataset.i);
    const action = button.dataset.action;
    if (action === "remove") steps.splice(i, 1);
    if (action === "up" && i > 0) [steps[i - 1], steps[i]] = [steps[i], steps[i - 1]];
    if (action === "down" && i < steps.length - 1) [steps[i + 1], steps[i]] = [steps[i], steps[i + 1]];
    editing(main, true);
    drawSteps();
  });
  main.querySelector("#c-add").addEventListener("click", () => {
    steps.push(main.querySelector("#c-add-name").value);
    editing(main, true);
    drawSteps();
  });
  const form = main.querySelector("#composite-form");
  form.addEventListener("input", () => editing(main, true));
  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    const test = { name: main.querySelector("#c-name").value.trim(), steps: [...steps] };
    const description = main.querySelector("#c-desc").value.trim();
    if (description) test.description = description;
    if (!test.steps.length) {
      toast("Add at least one step", "error");
      return;
    }
    const others = all.composites.filter((c) => c.name !== original?.name);
    if (others.some((c) => c.name === test.name)) {
      toast(`There is already a composite test named ${test.name}`, "error");
      return;
    }
    others.splice(original ? all.composites.indexOf(original) : others.length, 0, test);
    if (await saveComposites(others, all.compositeEtag)) {
      toast("Saved in admin/data/composite_tests.json", "success");
      editing(main, false);
      location.hash = "#/tests/composite";
    }
  });
  drawSteps();
}
