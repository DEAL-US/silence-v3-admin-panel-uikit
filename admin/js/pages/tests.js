async function unitList(main, app, tab) {
  const all = await loadAll();
  if (!all) return;
  const rows = all.units.filter((t) => t.source === tab);
  const resultOf = (t) => results["unit:" + t.name];

  main.innerHTML = `
    <h1>Tests</h1>
    <p class="uk-text-muted">Unit tests: one request each, and the status it should get. The panel sends them to your API
      in the order GET, POST, PUT, DELETE (the reads see the data before the changes). <strong>They change the
      database</strong>: reload its data (the scripts of <code>sql/</code>) to run them again from the start.</p>
    ${all.unitData.errors.length ? `<div class="uk-alert uk-alert-danger"><strong>Tests not loaded</strong>
      <ul>${all.unitData.errors.map((e) => `<li>${esc(e)}</li>`).join("")}</ul></div>` : ""}
    ${tabsHtml(tab, all.counts)}
    <div class="sa-toolbar">
      <button class="uk-button uk-button-primary" type="button" id="run">Run these ${rows.length}</button>
      ${tab === "auto"
        ? `<button class="uk-button uk-button-default" type="button" id="generate">Generate from the endpoints</button>`
        : `<a class="uk-button uk-button-default" href="#/tests/new">New unit test</a>`}
      <button class="uk-button uk-button-default" type="button" id="export">Export .http</button>
      <span class="sa-toolbar__spacer"></span>
      <span id="summary"></span>
    </div>
    <div id="grid"></div>`;

  const table = dataTable(main.querySelector("#grid"), {
    rows, sort: { key: "name", dir: "asc" },
    empty: tab === "auto" ? "No autogenerated tests: generate them from the endpoints." : "No custom tests yet.",
    columns: [
      { key: "actions", label: "", filter: false, sortable: false, className: "sa-actions", render: (t) =>
        iconButton("play", "Run", { action: "run" }) +
        (t.source === "auto"
          ? iconButton("pencil", "Customize (move to custom to change it)", { action: "customize" })
          : iconButton("pencil", "Edit", { href: link("tests", "edit", t.file, t.name) }) +
            iconButton("trash", "Delete", { action: "delete", danger: true })) },
      { key: "result", label: "Result", filter: "select",
        value: (t) => (resultOf(t) ? (resultOf(t).passed ? "PASS" : "FAIL") : ""), render: (t) => resultBadge(resultOf(t)) },
      { key: "name", label: "Test", render: (t) => `<strong>${esc(t.name)}</strong>` },
      { key: "request", label: "Request", className: "sa-nowrap", value: (t) => `${t.request.method} ${t.request.path}`,
        render: (t) => `${method(t.request.method)} <span class="sa-route">${esc(t.request.path)}</span>` },
      { key: "as", label: "As user", filter: "select", value: (t) => (t.request.as ?? null) === null ? "" : String(t.request.as),
        render: (t) => (t.request.as ?? null) === null ? `<span class="uk-text-muted">—</span>` : esc(t.request.as) },
      { key: "expect", label: "Expects", filter: "select", value: (t) => expectText(t.expect) },
      { key: "table", label: "Table", filter: "select" },
    ],
    after: (t) => (resultOf(t) && !resultOf(t).passed ? stepsDetail(resultOf(t).steps) : ""),
    onAction: async (action, t, button) => {
      if (action === "run") {
        if (t.request.method !== "GET" && !needsConfirm(button, "Run? It changes the database")) return;
        run([t]);
      }
      if (action === "customize") {
        if (!needsConfirm(button, "Move to custom?")) return;
        const res = await attempt(() => api(`/tests/${t.file}/${t.name}/customize`, "POST"), "Moved to custom");
        if (res) location.hash = link("tests", "edit", res.file, res.name);
      }
      if (action === "delete") {
        if (!needsConfirm(button, "Delete?")) return;
        if (await attempt(() => api(`/tests/${t.file}/${t.name}`, "DELETE", undefined, all.unitData.files[t.file] ?? ""), "Deleted")) {
          delete results["unit:" + t.name];
          await app.refreshStatus();
          unitList(main, app, tab);
        }
      }
    },
  });

  function summary() {
    const mine = rows.filter((t) => resultOf(t));
    const passed = mine.filter((t) => resultOf(t).passed).length;
    main.querySelector("#summary").innerHTML = mine.length
      ? `<span class="${passed === mine.length ? "sa-pass" : "sa-fail"}">${passed} / ${mine.length} passed</span>` : "";
  }

  async function run(tests) {
    const button = main.querySelector("#run");
    button.disabled = true;
    const label = button.textContent;
    button.innerHTML = `<span uk-spinner="ratio: .6"></span> Running…`;
    const ordered = [...tests].sort((a, b) => (ORDER[a.request.method] ?? 9) - (ORDER[b.request.method] ?? 9));
    const tokens = new Map();
    let passed = 0;
    for (const t of ordered) {
      const step = await runUnit(t.name, t, { source: `Test ${t.name}`, tokens });
      results["unit:" + t.name] = { passed: step.passed, steps: [step] };
      if (step.passed) passed++;
    }
    button.disabled = false;
    button.textContent = label;
    toast(`${passed} of ${ordered.length} tests passed`, passed === ordered.length ? "success" : "warning");
    table.update(rows);
    summary();
  }

  const runAll = main.querySelector("#run");
  runAll.addEventListener("click", () => {
    if (rows.some((t) => t.request.method !== "GET") && !needsConfirm(runAll, "Run them? They change the database")) return;
    run(rows);
  });
  main.querySelector("#export").addEventListener("click", async () => {
    const res = await attempt(() => api("/tests/export", "POST", { format: "http" }));
    if (res) toast(`Written: ${res.files.join(", ")}. Open them with VS Code's REST Client: sending them changes the database.`, "success");
  });
  const generate = main.querySelector("#generate");
  generate?.addEventListener("click", async () => {
    if (!needsConfirm(generate, "Overwrite the auto_ files?")) return;
    const res = await attempt(() => api("/tests/generate", "POST", {}));
    if (res) {
      toast(`${res.tables.reduce((n, x) => n + x.tests, 0)} tests generated`, "success");
      await app.refreshStatus();
      unitList(main, app, tab);
    }
  });
  summary();
}

async function unitEditor(main, file, name) {
  const all = await loadAll();
  if (!all) return;
  const t = file ? all.units.find((x) => x.file === file && x.name === name) : null;
  if (file && !t) {
    main.innerHTML = `<div class="uk-alert uk-alert-danger">There is no test ${esc(name)} in ${esc(file)}.json.</div>`;
    return;
  }
  main.innerHTML = `
    <h1>${t ? `Edit ${esc(t.name)}` : "New unit test"}</h1>
    <p class="sa-small uk-text-muted">One request: <code>"METHOD /path": body</code> (<code>null</code> without body),
      <code>as</code> (the id of the user, no password needed) and <code>expect</code> (a status, or an object with
      status, count, row and message; without it, a 2xx). <em>Try it</em> sends it to your API: it may change the database.</p>
    <form id="test-form">
      <div class="sa-form">
        <div class="sa-field"><label class="uk-form-label" for="t-name">Name</label>
          <input class="uk-input" id="t-name" name="name" value="${esc(t?.name ?? "")}" required pattern="\\w+"></div>
        <div class="sa-field"><label class="uk-form-label" for="t-file">File (tests/….json)</label>
          <input class="uk-input" id="t-file" name="file" value="${esc(t?.file ?? "")}" required pattern="[\\w\\-]+" placeholder="its table"></div>
      </div>
      <div class="sa-field"><label class="uk-form-label" for="t-data">Test (JSON)</label>
        <textarea class="uk-textarea sa-code sa-code--tall" id="t-data" name="data" spellcheck="false">${esc(JSON.stringify(t?.definition ?? UNIT_EXAMPLE, null, 2))}</textarea></div>
      <div class="sa-toolbar">
        <button class="uk-button uk-button-primary" type="submit">Save</button>
        <button class="uk-button uk-button-default" type="button" id="t-try">Try it</button>
        <a class="uk-button uk-button-default" href="#/tests/custom">Cancel</a>
      </div>
    </form>
    <div id="t-result"></div>`;

  const form = main.querySelector("#test-form");
  const parse = () => {
    try {
      return JSON.parse(form.querySelector("#t-data").value);
    } catch {
      toast("The test is not valid JSON", "error");
      return null;
    }
  };
  form.addEventListener("input", () => editing(main, true));
  main.querySelector("#t-try").addEventListener("click", async () => {
    const def = parse();
    if (!def) return;
    let unit;
    try {
      unit = parseUnit(def);
    } catch (error) {
      toast(error.message, "error");
      return;
    }
    const step = await runUnit(form.querySelector("#t-name").value || "(not saved)", unit, { source: "Try test" });
    main.querySelector("#t-result").innerHTML = `<h2>Result</h2>` + stepsDetail([step]);
  });
  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    const def = parse();
    if (!def) return;
    const v = Object.fromEntries(new FormData(form));
    const saved = await attempt(() => api(`/tests/${encodeURIComponent(v.file)}/${encodeURIComponent(v.name)}`, "PUT",
      def, all.unitData.files[v.file] ?? ""), `Saved in tests/${v.file}.json`);
    if (!saved) return;
    if (t && (t.name !== v.name || t.file !== v.file)) {
      const etag = t.file === v.file ? saved.etag : all.unitData.files[t.file] ?? "";
      await attempt(() => api(`/tests/${t.file}/${t.name}`, "DELETE", undefined, etag));
    }
    editing(main, false);
    location.hash = "#/tests/custom";
  });
}

