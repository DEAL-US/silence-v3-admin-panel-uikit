// Tests. Unit tests (tests/auto_<table>.json and tests/<table>.json): Silence generates and keeps
// them. Composite tests (sequences of unit tests, by name): the panel keeps them
// (admin/data/composite_tests.json). Silence does not run tests: the panel runs both against the
// student's API, so they change the database.
// Views: #/tests/auto, #/tests/custom, #/tests/composite (grids), #/tests/new,
// #/tests/edit/<file>/<name>, #/tests/composite/new and #/tests/composite/edit/<name>.
import { api, esc, attempt, toast, needsConfirm, editing, link, method, iconButton, statusClass, json,
  callApi, studentApi } from "../ui.js";
import { dataTable } from "../components/table.js";

const TABS = { auto: "Autogenerated", custom: "Custom", composite: "Composite" };
const COMPOSITE_DATA = "composite_tests";
// The order in which the unit tests run: the reads see the data before the changes
const ORDER = { GET: 0, POST: 1, PUT: 2, DELETE: 3 };

// The results of the last runs, while the panel is open ("unit:<name>", "composite:<name>")
const results = {};

const UNIT_EXAMPLE = {
  description: "Describe what the test checks",
  "GET /my_table/1": null,
  as: 1,
  expect: 200,
};

export function crumbs(params) {
  const [view, a, b] = params;
  const base = [{ label: "Tests", href: "#/tests" }];
  if (view === "edit") return [...base, { label: "Custom", href: "#/tests/custom" }, { label: `${a}/${b}` }];
  if (view === "new") return [...base, { label: "Custom", href: "#/tests/custom" }, { label: "New unit test" }];
  if (view === "composite" && a === "edit") return [...base, { label: "Composite", href: "#/tests/composite" }, { label: b }];
  if (view === "composite" && a === "new") return [...base, { label: "Composite", href: "#/tests/composite" }, { label: "New composite test" }];
  return [...base, { label: TABS[view] ?? TABS.auto }];
}

export function parent(params) {
  const [view, a] = params;
  if (view === "edit" || view === "new") return "#/tests/custom";
  if (view === "composite" && (a === "edit" || a === "new")) return "#/tests/composite";
  return null;
}

export async function render(main, app, params) {
  const [view, a, b] = params;
  if (view === "edit") return unitEditor(main, a, b);
  if (view === "new") return unitEditor(main, null, null);
  if (view === "composite" && a === "edit") return compositeEditor(main, b);
  if (view === "composite" && a === "new") return compositeEditor(main, null);
  if (view === "composite") return compositeList(main);
  return unitList(main, app, view === "custom" ? "custom" : "auto");
}

function tabsHtml(tab, counts) {
  return `<ul class="uk-tab sa-tabs">
    ${Object.entries(TABS).map(([key, label]) =>
      `<li class="${key === tab ? "uk-active" : ""}"><a href="#/tests/${key}">${label} (${counts[key] ?? 0})</a></li>`).join("")}
  </ul>`;
}

async function loadAll() {
  const [unitData, composite] = await Promise.all([attempt(() => api("/tests")), attempt(() => api(`/panel-data/${COMPOSITE_DATA}`))]);
  if (!unitData || !composite) return null;
  const units = unitData.tests;
  const composites = Array.isArray(composite.data) ? composite.data : [];
  return {
    unitData, units, composites, compositeEtag: composite.etag,
    counts: {
      auto: units.filter((t) => t.source === "auto").length,
      custom: units.filter((t) => t.source === "custom").length,
      composite: composites.length,
    },
  };
}

function stepsDetail(steps) {
  return steps.map((s) => `
    <div class="sa-step ${s.passed ? "sa-step--pass" : "sa-step--fail"} sa-small">
      ${steps.length > 1 ? `Step ${s.index + 1} (<strong>${esc(s.test)}</strong>): ` : ""}${s.method ? method(s.method) : ""} <span class="sa-route">${esc(s.path)}</span>
      ${s.status ? `→ <span class="sa-status ${statusClass(s.status)}">${s.status}</span>` : ""}
      ${s.failures.length ? `<br>${s.failures.map(esc).join("<br>")}
        ${s.response !== undefined ? `<details><summary>Response</summary><pre class="sa-pre">${json(s.response)}</pre></details>` : ""}` : ""}
    </div>`).join("");
}

function resultBadge(r) {
  if (!r) return `<span class="uk-text-muted">—</span>`;
  return r.passed ? `<span class="sa-pass">PASS</span>` : `<span class="sa-fail">FAIL</span>`;
}

function expectText(expect) {
  return expect.status ? String(expect.status) : "2xx";
}

