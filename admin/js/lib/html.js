// HTML that is safe by default: html`...` escapes every value that it interpolates, except the
// ones that are already HTML (another html`...`, or raw() for HTML built on purpose). Lists are
// joined; null, undefined and false are left out. Assign the result to innerHTML as it is.
// And the small pieces of markup that the pages share. Without DOM: it can be tested with node.

class Html {
  constructor(text) {
    this.text = text;
  }

  toString() {
    return this.text;
  }
}

/** Escapes a value to put it in HTML (text or the value of an attribute between quotes). */
export function esc(value) {
  return String(value ?? "").replace(/[&<>"']/g, (c) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[c]);
}

/** HTML built on purpose, which is not escaped. */
export const raw = (text) => new Html(String(text ?? ""));

function piece(value) {
  if (value === null || value === undefined || value === false) return "";
  if (value instanceof Html) return value.text;
  if (Array.isArray(value)) return value.map(piece).join("");
  return esc(value);
}

export function html(strings, ...values) {
  let text = strings[0];
  values.forEach((value, i) => {
    text += piece(value) + strings[i + 1];
  });
  return new Html(text);
}

/** A value as JSON, to show it in a <pre> (a text as it is). */
export const json = (value) => (typeof value === "string" ? value : JSON.stringify(value, null, 2));

/** A link inside the panel (#/...), with its parts encoded. */
export function link(...parts) {
  return "#/" + parts.map((p) => encodeURIComponent(p)).join("/");
}

/** A small icon button for the actions of a grid row: a link (href) or a button (action). */
export function iconButton(icon, title, { href, action, danger = false, disabled = false } = {}) {
  const cls = `uk-icon-button sa-icon-button${danger ? " sa-icon-button--danger" : ""}`;
  return href
    ? html`<a class="${cls}" href="${href}" uk-icon="icon: ${icon}; ratio: .8" title="${title}" aria-label="${title}"></a>`
    : html`<button class="${cls}" type="button" data-action="${action}" uk-icon="icon: ${icon}; ratio: .8"
        title="${title}" aria-label="${title}" ${disabled ? "disabled" : ""}></button>`;
}

/** The head of a page, fixed under the top bar while it scrolls: its title and, under it, what
 *  else must stay in sight (tabs, the toolbar of the page) */
export const pageHead = (title, extra = "") => html`<div class="sa-pagehead"><h1>${title}</h1>${extra}</div>`;

export const methodBadge = (m) => html`<span class="sa-method sa-method--${m}">${m}</span>`;

const SOURCES = { auto: "Autogenerated", custom: "Custom" };

/** Whether an endpoint or a test is autogenerated or custom */
export const sourceBadge = (s) => html`<span class="uk-label sa-label-${s} sa-label-small" title="${SOURCES[s] ?? s}">${s}</span>`;

export function statusClass(code) {
  if (code < 400) return "sa-status--ok";
  if (code < 500) return "sa-status--client";
  return "sa-status--server";
}

export const muted = (text = "—") => html`<span class="uk-text-muted">${text}</span>`;

/** Tabs: [{key, label, href, disabled (why it cannot be opened)}], the active one by its key */
export function tabs(items, active) {
  return html`<ul class="uk-tab sa-tabs" role="tablist">
    ${items.map((t) => (t.disabled
      ? html`<li class="uk-disabled" title="${t.disabled}"><a role="tab" aria-selected="false" aria-disabled="true">${t.label}</a></li>`
      : html`<li class="${t.key === active ? "uk-active" : ""}"><a role="tab" aria-selected="${t.key === active}"
          href="${t.href}">${t.label}</a></li>`))}
  </ul>`;
}

/** A switch (a checkbox): attrs, the attributes of the input (name, data-...) as an object */
export function switchControl({ checked, label, disabled = false, title = "", attrs = {} }) {
  const extra = Object.entries(attrs).map(([k, v]) => html` ${k}="${v}"`);
  return html`<label class="sa-switch" title="${title}">
    <input type="checkbox"${extra} ${checked ? "checked" : ""} ${disabled ? "disabled" : ""} aria-label="${label}">
    <span class="sa-switch__slider"></span></label>`;
}

/** A row with a switch and its text (the text may be HTML) */
export const switchRow = (options, text) => html`<div class="sa-switch-row">${switchControl(options)} <span>${text}</span></div>`;

/** The options of a select: values (or [value, text]), the selected one and an empty first one */
export function options(values, selected, empty) {
  return html`${empty !== undefined ? html`<option value="">${empty}</option>` : ""}${values.map((v) => {
    const [value, text] = Array.isArray(v) ? v : [v, v];
    return html`<option value="${value}" ${String(value) === String(selected ?? "") ? "selected" : ""}>${text}</option>`;
  })}`;
}

/** An alert that lists messages (e.g., the errors of the files) */
export function alertList(kind, title, items) {
  return items.length
    ? html`<div class="uk-alert uk-alert-${kind}"><strong>${title}</strong><ul>${items.map((e) => html`<li>${e}</li>`)}</ul></div>`
    : "";
}
